final class ClipboardMonitorTests: StoredClipboardTestCase {
  private var monitor: ClipboardMonitor!
  override func setUpWithError() throws {
    try super.setUpWithError()
    makeMonitor()
  }

  private func resetFixture() throws {
    monitor?.stop()
    try resetStorage()
    makeMonitor()
  }

  private func makeMonitor() {
    monitor = ClipboardMonitor(pasteboard: pasteboard, store: store, cacheService: cache, settings: settings, frontmostApp: { (nil, nil) })
  }

  override func tearDownWithError() throws {
    monitor.stop()
    monitor = nil
    try super.tearDownWithError()
  }

  func testConfidentialAndTransientClipboardMarkersNeverPersist() {
    settings.excludeSensitive = false
    settings.ignoredApps = []
    for marker in [
      "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    ] {
      pasteboard.clearContents()
      pasteboard.setString("innocent-looking confidential value", forType: .string)
      pasteboard.setData(Data(), forType: .init(marker))
      monitor.pollNowAndWait()
      RunLoop.main.run(until: Date().addingTimeInterval(0.02))
      XCTAssertTrue(store.items.isEmpty, marker)
    }
  }

  func testIgnoredRepresentationsNeverFallBackToTextOrWriteManagedFiles() throws {
    let cases: [(ClipKind, () -> Void, String?)] =
      [
        (.image, { XCTAssertTrue(self.pasteboard.writeObjects([testImage(color: .systemOrange)])) }, nil),
        (
          .richText,
          {
            XCTAssertTrue(self.pasteboard.setData(Data("<strong>Ignored HTML</strong> clipboard text".utf8), forType: .html))
            XCTAssertTrue(self.pasteboard.setString("Ignored HTML clipboard text", forType: .string))
          }, "Skipped: Rich Text items are ignored in capture settings."
        ),
      ]
      + [(.pdf, NSPasteboard.PasteboardType.pdf), (.audio, .sound), (.video, VideoPayload.pasteboardTypes[0]), (.richText, .rtf)].map {
        kind, type in
        (
          kind,
          {
            XCTAssertTrue(self.pasteboard.setData(Data("ignored representation".utf8), forType: type))
            XCTAssertTrue(self.pasteboard.setString("Do not persist this fallback", forType: .string))
          }, "items are ignored"
        )
      }
      + ["https://example.com/private", "example.com/private", "mailto:private@example.com"].map { link in
        (.url, { XCTAssertTrue(self.pasteboard.setString(link, forType: .string)) }, "Skipped: Link items are ignored in capture settings.")
      }
    for (kind, write, expectedStatus) in cases {
      try resetFixture()
      settings.ignoredItemKindsRaw = [kind.rawValue]
      pasteboard.clearContents()
      write()
      monitor.pollNowAndWait()
      settle(0.05)
      cache.flushForTesting()
      XCTAssertTrue(store.items.isEmpty, "\(kind) must stop capture before plaintext fallback")
      let files = try FileManager.default.contentsOfDirectory(
        at: directory.appendingPathComponent(kind == .image ? "images" : "attachments"), includingPropertiesForKeys: nil)
      XCTAssertTrue(files.isEmpty, "\(kind) must not write managed files")
      if expectedStatus == "items are ignored" {
        XCTAssertTrue(settings.status(.capture).contains("items are ignored"), "\(kind)")
      } else if let expectedStatus {
        XCTAssertEqual(settings.status(.capture), expectedStatus)
      }
    }
  }

}
final class PasteActionServiceTests: StoredClipboardTestCase {

  func testPasteSoundWaitsForDeliveryAndIsSilentIfTheTargetOrClipboardChanges() throws {
    let target = try makeRunningTargetApp()
    var foreground: pid_t? = target.processIdentifier
    var scheduled: (() -> Void)?
    var posts = 0
    var postSucceeds = true
    var cues: [TransferSound] = []
    let service = PasteActionService(
      pasteboard: pasteboard, cacheService: cache, accessibilityPermissionProvider: { true }, targetActivator: { _ in true },
      keyboardPasteScheduler: { scheduled = $0 }, feedback: { cues.append($0) }, frontmostPID: { foreground },
      keyboardPastePoster: {
        posts += 1
        return postSucceeds
      })
    let item = makeTextItem("Paste timing")
    XCTAssertEqual(service.transfer(.clip(item), .paste, targetApp: target), .pasteScheduled())
    XCTAssertTrue(cues.isEmpty, "Scheduling and writing the pasteboard are not a completed paste")
    scheduled?()
    XCTAssertEqual(cues, [.paste])
    XCTAssertEqual(posts, 1)
    _ = service.transfer(.plain(item), .paste, targetApp: target)
    scheduled?()
    XCTAssertEqual(cues, [.paste, .paste])
    _ = service.transfer(.clip(item), .paste, targetApp: target)
    foreground = nil
    scheduled?()
    XCTAssertEqual(posts, 2)
    foreground = target.processIdentifier
    _ = service.transfer(.clip(item), .paste, targetApp: target)
    pasteboard.clearContents()
    scheduled?()
    XCTAssertEqual(posts, 2)
    _ = service.transfer(.clip(item), .paste, targetApp: target)
    postSucceeds = false
    scheduled?()
    XCTAssertEqual(cues, [.paste, .paste])
  }

  func testUnwritableSingleAndBatchCopiesPreserveTheClipboard() {
    let missing = testItem(
      kind: .file, displayText: "Missing file", payload: "/tmp/goldfish-missing-\(UUID())", payloadHash: "hash", createdAt: Date(),
      lastUsedAt: Date(), useCount: 0)
    let batchMissing = testItem(
      kind: .file, displayText: "Missing file",
      payload: FileManager.default.temporaryDirectory.appendingPathComponent("goldfish-missing-\(UUID())").path, payloadHash: "hash",
      createdAt: Date(), lastUsedAt: Date(), useCount: 0)
    let cases: [(items: [Clip], batch: Bool, error: String)] = [
      ([makeTextItem("Writable"), batchMissing], true, "Could not write items to clipboard."),
      ([missing], false, "Could not write item to clipboard."), ([makeTextItem("")], false, "Could not write item to clipboard."),
    ]
    for entry in cases {
      let service = makeService()
      pasteboard.clearContents()
      XCTAssertTrue(pasteboard.setString("keep me", forType: .string))
      XCTAssertEqual(entry.batch ? service.transfer(.clips(entry.items)) : service.transfer(.clip(entry.items[0])), .failed(entry.error))
      XCTAssertEqual(pasteboard.string(forType: .string), "keep me")
    }
  }
  private func makeService(
    accessibilityPermissionProvider: @escaping () -> Bool = { false },
    targetActivator: @escaping (NSRunningApplication) -> Bool = { _ in false },
    keyboardPasteScheduler: @escaping (@escaping () -> Void) -> Void = { _ in }
  ) -> PasteActionService {
    PasteActionService(
      pasteboard: pasteboard, cacheService: cache, accessibilityPermissionProvider: accessibilityPermissionProvider,
      targetActivator: targetActivator, keyboardPasteScheduler: keyboardPasteScheduler)
  }

  private func makeTextItem(_ value: String) -> Clip {
    testItem(payload: value, payloadHash: "hash", createdAt: Date(), lastUsedAt: Date(), useCount: 0)
  }

  private func makeRunningTargetApp() throws -> NSRunningApplication {
    try XCTUnwrap(NSWorkspace.shared.runningApplications.first { !$0.isTerminated && $0.processIdentifier > 0 })
  }

}
