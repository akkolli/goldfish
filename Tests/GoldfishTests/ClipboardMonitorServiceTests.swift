  func testIgnoredAttachmentsNeverFallBackToPlainTextOrWriteManagedFiles() throws {
    let cases: [(ClipboardItemKind, NSPasteboard.PasteboardType)] = [
      (.pdf, .pdf), (.audio, .sound), (.video, VideoPayload.pasteboardTypes[0]), (.richText, .rtf),
    ]
    for (kind, type) in cases {
      try resetFixture()
      settings.ignoredItemKindsRaw = [kind.rawValue]
      pasteboard.clearContents()
      XCTAssertTrue(pasteboard.setData(Data("ignored representation".utf8), forType: type))
      XCTAssertTrue(pasteboard.setString("Do not persist this fallback", forType: .string))
      monitor.pollNowAndWait()
      RunLoop.main.run(until: Date().addingTimeInterval(0.05))
      cache.flushForTesting()
      XCTAssertTrue(store.items.isEmpty, "\(kind) must stop capture before plaintext fallback")
      XCTAssertTrue(try attachmentFileURLs(in: directory).isEmpty, "\(kind) must not write attachments")
      XCTAssertTrue(settings.captureStatusMessage.contains("items are ignored"), "\(kind)")
    }
  }

  private func makeTempFile(contents: String) throws -> URL {
    let baseURL = try makeTempDirectory()
    let fileURL = baseURL.appendingPathComponent("payload.txt")
    try contents.write(to: fileURL, atomically: true, encoding: .utf8)
    return fileURL
  }

  private func imageCacheFileURLs(in baseURL: URL) throws -> [URL] {
    let imageDirectory = baseURL.appendingPathComponent("images", isDirectory: true)
    return try FileManager.default.contentsOfDirectory(at: imageDirectory, includingPropertiesForKeys: nil)
  }

  private func attachmentFileURLs(in baseURL: URL) throws -> [URL] {
    let attachmentDirectory = baseURL.appendingPathComponent("attachments", isDirectory: true)
    return try FileManager.default.contentsOfDirectory(at: attachmentDirectory, includingPropertiesForKeys: nil)
  }

