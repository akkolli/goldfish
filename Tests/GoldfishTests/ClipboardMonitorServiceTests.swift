import AppKit
import Foundation
import XCTest

@testable import Goldfish

final class ClipboardMonitorServiceTests: StoredClipboardTestCase {
  private var monitor: ClipboardMonitorService!
  override func setUpWithError() throws {
    try super.setUpWithError()
    makeMonitor()
  }

  private func resetFixture() throws {
    monitor?.stop()
    try resetStorage()
    makeMonitor()
  }

  private func makeMonitor() {
    monitor = ClipboardMonitorService(
      pasteboard: pasteboard, store: store, cacheService: cache, settings: settings, frontmostApp: { (nil, nil) })
  }

  override func tearDownWithError() throws {
    monitor.stop()
    monitor = nil
    try super.tearDownWithError()
  }

  func testStartupAndResumeDoNotCaptureEarlierClipboardContents() {
    let pasteboard = self.pasteboard
    pasteboard.clearContents()
    pasteboard.setString("Copied during setup", forType: .string)
    monitor.start()
    monitor.pollNowAndWait()
    RunLoop.main.run(until: Date().addingTimeInterval(0.03))
    XCTAssertTrue(store.items.isEmpty)
    monitor.setPaused(true)
    pasteboard.clearContents()
    pasteboard.setString("Copied while paused", forType: .string)
    monitor.pollNowAndWait()
    monitor.setPaused(false)
    monitor.pollNowAndWait()
    RunLoop.main.run(until: Date().addingTimeInterval(0.03))
    XCTAssertTrue(store.items.isEmpty)
    let captured = expectation(description: "capture after resume")
    monitor.onCapturedItem = { _ in captured.fulfill() }
    pasteboard.clearContents()
    pasteboard.setString("Copied after resuming", forType: .string)
    monitor.pollNowAndWait()
    wait(for: [captured], timeout: 1)
    XCTAssertEqual(store.items.map(\.payload), ["Copied after resuming"])
    monitor.stop()
  }

  func testConfidentialAndTransientClipboardMarkersNeverPersist() {
    settings.excludeSensitive = false
    settings.ignoredApps = []
    for marker in [
      "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    ] {
      pasteboard.clearContents()
      pasteboard.setString("innocent-looking confidential value", forType: .string)
      pasteboard.setData(Data(), forType: .init(marker))
      monitor.pollNowAndWait()
      RunLoop.main.run(until: Date().addingTimeInterval(0.02))
      XCTAssertTrue(store.items.isEmpty, marker)
    }
  }

  func testHexTextCapturesAsColorAndHonorsColorExclusion() {
    let captured = expectation(description: "hex swatch")
    monitor.onCapturedItem = { _ in captured.fulfill() }
    pasteboard.clearContents()
    pasteboard.setString("#3b82f6", forType: .string)
    monitor.pollNowAndWait()
    wait(for: [captured], timeout: 1)
    XCTAssertEqual(store.items.first?.kind, .color)
    settings.ignoredItemKindsRaw = [ClipboardItemKind.color.rawValue]
    pasteboard.clearContents()
    pasteboard.setString("#f80", forType: .string)
    monitor.pollNowAndWait()
    RunLoop.main.run(until: Date().addingTimeInterval(0.02))
    XCTAssertEqual(store.items.count, 1)
    XCTAssertEqual(ColorPayload.displayHex(from: "#f80"), "#FF8800")
    XCTAssertFalse(ColorPayload.isHexColorLiteral("#Heading"))
    XCTAssertFalse(ColorPayload.isHexColorLiteral("123456"))
  }

  func testPollNowCapturesCodeSnippetAsCode() {
    settings.pruneDuplicates = false
    let snippet = "func greet(name: String) -> String {\n  return \"Hi \\(name)\"\n}"

    let captured = expectation(description: "code snippet captured")
    store.observeItems { items in if items.contains(where: { $0.kind == .code && $0.payload == snippet }) { captured.fulfill() } }

    let pasteboard = self.pasteboard
    pasteboard.clearContents()
    XCTAssertTrue(pasteboard.setString(snippet, forType: .string))

    monitor.pollNowAndWait()
    wait(for: [captured], timeout: 1.0)

    let item = store.items.first
    XCTAssertEqual(item?.kind, .code)
    XCTAssertEqual(item?.displayText, "Swift Snippet")
    XCTAssertEqual(item?.payload, snippet)
  }

  func testPollNowCapturesPDFSoundAndVideoAsRestorableAttachments() throws {
    let cases: [(ClipboardItemKind, NSPasteboard.PasteboardType, Data)] = [
      (.pdf, .pdf, Data("%PDF-1.4\nclipbored\n%%EOF".utf8)), (.audio, .sound, Data([1, 2, 3, 4, 8, 16])),
      (.video, VideoPayload.pasteboardTypes[0], Data([0, 0, 0, 24, 102, 116, 121, 112, 109, 112, 52, 50])),
    ]
    for (kind, type, data) in cases {
      try resetFixture()
      let captured = expectation(description: "\(kind) captured")
      store.observeItems { items in if items.contains(where: { $0.kind == kind }) { captured.fulfill() } }
      pasteboard.clearContents()
      XCTAssertTrue(pasteboard.setData(data, forType: type))
      monitor.pollNowAndWait()
      wait(for: [captured], timeout: 1)
      let item = try XCTUnwrap(store.items.first(where: { $0.kind == kind }))
      XCTAssertTrue(FileManager.default.fileExists(atPath: item.payload))
      if kind == .video { XCTAssertEqual(item.displayText, VideoPayload.displayTitle(byteCount: data.count)) }
      XCTAssertEqual(cache.data(for: item.payload), data)
      XCTAssertEqual(
        (PasteActionService(pasteboard: pasteboard, cacheService: cache).pasteboardWriters(for: item).first as? NSPasteboardItem)?.types
          .first, type)
      XCTAssertEqual(PasteActionService(pasteboard: pasteboard, cacheService: cache).copy(item), .copied)
      XCTAssertEqual(pasteboard.data(forType: type), data)
    }
  }

  func testPollNowCapturesColorAsRestorableSwatch() throws {
    let color = NSColor(deviceRed: 10 / 255, green: 132 / 255, blue: 255 / 255, alpha: 1)
    let captured = expectation(description: "color captured")

    store.observeItems { items in if items.contains(where: { $0.kind == .color && $0.payload == "#0A84FF" }) { captured.fulfill() } }

    let pasteboard = self.pasteboard
    pasteboard.clearContents()
    XCTAssertTrue(pasteboard.writeObjects([color]))

    monitor.pollNowAndWait()
    wait(for: [captured], timeout: 1.0)

    let item = try XCTUnwrap(store.items.first(where: { $0.kind == .color }))
    XCTAssertEqual(item.displayText, "#0A84FF")
    XCTAssertEqual(item.payload, "#0A84FF")
    XCTAssertEqual(PasteActionService(pasteboard: pasteboard, cacheService: cache).copy(item), .copied)
    let restored = try XCTUnwrap(NSColor(from: pasteboard))
    XCTAssertEqual(ColorPayload.hexString(from: restored), "#0A84FF")
    XCTAssertEqual(pasteboard.string(forType: .string), "#0A84FF")
  }

  func testPollNowCapturesMultipleFileReferencesAsOneRestorableItem() throws {
    let firstURL = try makeTempFile(contents: "first file reference")
    let secondURL = try makeTempFile(contents: "second file reference")
    let payload = FilePayload.payload(from: [firstURL, secondURL])
    let captured = expectation(description: "multiple file references captured")

    store.observeItems { items in if items.contains(where: { $0.kind == .file && $0.payload == payload }) { captured.fulfill() } }

    let pasteboard = self.pasteboard
    pasteboard.clearContents()
    XCTAssertTrue(pasteboard.writeObjects([firstURL as NSURL, secondURL as NSURL]))

    monitor.pollNowAndWait()
    wait(for: [captured], timeout: 1.0)

    let item = try XCTUnwrap(store.items.first)
    XCTAssertEqual(item.kind, .file)
    XCTAssertEqual(item.displayText, "2 files")
    XCTAssertEqual(item.payload, payload)
    XCTAssertEqual(PasteActionService(pasteboard: pasteboard, cacheService: cache).copy(item), .copied)
    let objects = pasteboard.readObjects(forClasses: [NSURL.self], options: nil) as? [URL]
    XCTAssertEqual(objects?.map(\.standardizedFileURL), [firstURL.standardizedFileURL, secondURL.standardizedFileURL])
  }

