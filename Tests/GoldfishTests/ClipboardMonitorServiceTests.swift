  func testPollNowPrefersRichTextOverPlainStringFallback() throws {
    let text = "Rich clipboard text"
    let attributed = NSAttributedString(string: text, attributes: [.font: NSFont.boldSystemFont(ofSize: 13)])
    let rtfData = try XCTUnwrap(attributed.rtf(from: NSRange(location: 0, length: attributed.length), documentAttributes: [:]))
    let captured = expectation(description: "rich text captured")

    store.observeItems { items in if items.contains(where: { $0.kind == .richText && $0.displayText == text }) { captured.fulfill() } }

    let pasteboard = self.pasteboard
    pasteboard.clearContents()
    XCTAssertTrue(pasteboard.setData(rtfData, forType: .rtf))
    XCTAssertTrue(pasteboard.setString(text, forType: .string))

    monitor.pollNowAndWait()
    wait(for: [captured], timeout: 1.0)

    XCTAssertEqual(store.items.first?.kind, .richText)
    let item = try XCTUnwrap(store.items.first)
    XCTAssertEqual(item.displayText, text)
    XCTAssertTrue(FileManager.default.fileExists(atPath: item.payload))
    XCTAssertEqual(cache.data(for: item.payload), rtfData)
    XCTAssertEqual(PasteActionService(pasteboard: pasteboard, cacheService: cache).copy(item), .copied)
    XCTAssertEqual(pasteboard.data(forType: .rtf), rtfData)
    XCTAssertEqual(pasteboard.string(forType: .string), text)
  }

